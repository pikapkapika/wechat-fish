/** 微信回复红线。只拦明确特征，不把普通口语、地名当成攻击。 */
const RULES = [
  ['family-insult', /(?:操|艹|草|肏|去你|滚你|死)[你妳您他她]?(?:妈|娘|爹|爸|全家)|[你妳您](?:妈的|妈逼|妈死|全家死)|妈了个|狗娘养/iu],
  ['profanity', /傻[逼比b]|煞笔|沙比|牛逼|装逼|他妈的|特么|他么|妈蛋|卧槽|我操|我艹|我草|操你|草你|去死|贱人|婊子?|狗东西|畜生|王八蛋|混蛋|智障|废物/iu],
  ['regional-attack', /地域狗|地域黑|河南偷井盖|(?:河南|东北|山东|广东|上海|北京|四川|湖南|湖北|安徽|江苏|浙江|福建|江西|广西|河北|山西|陕西|云南|贵州|重庆|天津|新疆|西藏|内蒙|香港|台湾)(?:人)?(?:都是|全是|就是|只会|就会)(?:贼|骗子|小偷|垃圾|废物)|(?:外地狗|乡巴佬|穷逼|死胖子|丑八怪)/u],
  ['sarcasm', /倒是|就这|也配|你说第.{1,8}遍了|嘴硬|[😑🙄😒]|你(?:这|那|的)?(?:水平|智商)|你(?:真|可真|也太)?(?:蠢|笨)|没脑子/u],
];

export function checkReply(text) {
  const value = String(text ?? '').normalize('NFKC');
  for (const [reason, pattern] of RULES) {
    if (pattern.test(value)) return { ok: false, reason: `redline:${reason}` };
  }
  return { ok: true, reason: '' };
}
